import multiprocessing
import os
import stat
import sys

if sys.version_info[0] < 3:
    from urllib2 import urlopen
else:
    from urllib.request import urlopen

TARGET = os.path.join(os.path.dirname(__file__), 'Orthanc')
PLUGIN_SDK_VERSION_OLD = [ ]
PLUGIN_SDK_VERSION_NEW = [ '1.13.0' ]
HAS_PROTOCOL_BUFFERS = [ '1.13.0' ]
REPOSITORY = 'https://orthanc.uclouvain.be/hg/orthanc/raw-file'

# The tag of the Orthanc release that every file comes from
ORTHANC_RELEASE = 'Orthanc-1.13.0'

# "DownloadOrthancFramework.cmake" of a release does not know the MD5 of its
# own source archive (Orthanc adds it to mainline afterwards). The build uses
# "Resources/Orthanc-1.13.0.tar.gz" and checks it against this hash.
FRAMEWORK_MD5 = {
    '1.13.0' : 'cc95d3e509612b541e10e91c831fbfe3',
}

FILES = [
    (ORTHANC_RELEASE, 'OrthancFramework/Resources/CMake/AutoGeneratedCode.cmake', 'CMake'),
    (ORTHANC_RELEASE, 'OrthancFramework/Resources/CMake/Compiler.cmake', 'CMake'),
    (ORTHANC_RELEASE, 'OrthancFramework/Resources/CMake/DownloadOrthancFramework.cmake', 'CMake'),
    (ORTHANC_RELEASE, 'OrthancFramework/Resources/CMake/DownloadPackage.cmake', 'CMake'),
    (ORTHANC_RELEASE, 'OrthancFramework/Resources/CMake/EmbedResources.py', 'CMake'),
    (ORTHANC_RELEASE, 'OrthancFramework/Resources/CMake/GoogleTestConfiguration.cmake', 'CMake'),
    (ORTHANC_RELEASE, 'OrthancFramework/Resources/CMake/OpenSslConfiguration.cmake', 'CMake'),
    (ORTHANC_RELEASE, 'OrthancFramework/Resources/CMake/ProtobufConfiguration.cmake', 'CMake'),
    (ORTHANC_RELEASE, 'OrthancFramework/Resources/Toolchains/LinuxStandardBaseToolchain.cmake', 'Toolchains'),
    (ORTHANC_RELEASE, 'OrthancFramework/Resources/Toolchains/MinGW-W64-Toolchain32.cmake', 'Toolchains'),
    (ORTHANC_RELEASE, 'OrthancFramework/Resources/Toolchains/MinGW-W64-Toolchain64.cmake', 'Toolchains'),
    (ORTHANC_RELEASE, 'OrthancFramework/Resources/Toolchains/MinGWToolchain.cmake', 'Toolchains'),
    (ORTHANC_RELEASE, 'OrthancServer/Plugins/Samples/Common/ExportedSymbolsPlugins.list', 'Plugins'),
    (ORTHANC_RELEASE, 'OrthancServer/Plugins/Samples/Common/OrthancPluginCppWrapper.cpp', 'Plugins'),
    (ORTHANC_RELEASE, 'OrthancServer/Plugins/Samples/Common/OrthancPluginCppWrapper.h', 'Plugins'),
    (ORTHANC_RELEASE, 'OrthancServer/Plugins/Samples/Common/OrthancPluginException.h', 'Plugins'),
    (ORTHANC_RELEASE, 'OrthancServer/Plugins/Samples/Common/OrthancPluginsExports.cmake', 'Plugins'),
    (ORTHANC_RELEASE, 'OrthancServer/Plugins/Samples/Common/VersionScriptPlugins.map', 'Plugins'),
]

SDK = [
    'orthanc/OrthancCPlugin.h',
    'orthanc/OrthancCDatabasePlugin.h',
]

SDK_PROTOCOL_BUFFERS = [
    'orthanc/OrthancCPlugin.h',
    'orthanc/OrthancCDatabasePlugin.h',
    'orthanc/OrthancDatabasePlugin.proto',
]


def Download(x):
    branch = x[0]
    source = x[1]
    target = os.path.join(TARGET, x[2])
    print(target)

    try:
        os.makedirs(os.path.dirname(target))
    except:
        pass

    url = '%s/%s/%s' % (REPOSITORY, branch, source)

    try:
        with open(target, 'wb') as f:
            f.write(urlopen(url).read())
    except Exception as e:
        raise Exception('Cannot download: %s' % url)    

    
commands = []

for f in FILES:
    commands.append([ f[0],  # Branch
                      f[1],  # Source file
                      os.path.join(f[2], os.path.basename(f[1])) ])

for version in PLUGIN_SDK_VERSION_OLD:
    for f in SDK:
        commands.append([
            'Orthanc-%s' % version, 
            'Plugins/Include/%s' % f,
            'Sdk-%s/%s' % (version, f) 
        ])

for version in PLUGIN_SDK_VERSION_NEW:
    if version in HAS_PROTOCOL_BUFFERS:
        files = SDK_PROTOCOL_BUFFERS
    else:
        files = SDK
    
    for f in files:
        commands.append([
            'Orthanc-%s' % version, 
            'OrthancServer/Plugins/Include/%s' % f,
            'Sdk-%s/%s' % (version, f) 
        ])


pool = multiprocessing.Pool(10)  # simultaneous downloads
pool.map(Download, commands)


# Add the MD5 of the source archive of each release that is not known yet
path = os.path.join(TARGET, 'CMake', 'DownloadOrthancFramework.cmake')
with open(path, 'r') as f:
    cmake = f.read()

# The official releases come first, each with its "set(...MD5...)" line, and end
# with a blank line before the development snapshots: a new release goes there
SNAPSHOTS = '\n      # Below this point are development snapshots'

for version, md5 in sorted(FRAMEWORK_MD5.items()):
    line = '      elseif (ORTHANC_FRAMEWORK_VERSION STREQUAL "%s")\n' % version
    if line not in cmake:
        if SNAPSHOTS not in cmake:
            raise Exception('Cannot add the MD5 of Orthanc %s to %s' % (version, path))
        j = cmake.index(SNAPSHOTS)
        cmake = (cmake[:j] + line +
                 '        set(ORTHANC_FRAMEWORK_MD5 "%s")\n' % md5 + cmake[j:])

with open(path, 'w') as f:
    f.write(cmake)
